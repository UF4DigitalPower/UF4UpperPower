static inline const uint8_t *Teko_SemiBold_FindBitmap(char ch, LCD_FontSize size) {
	uint32_t glyph_index;
	for (glyph_index = 0U; glyph_index < (sizeof(teko_semibold_glyphs) / sizeof(teko_semibold_glyphs[0])); ++glyph_index) {
		uint32_t size_index;
		if (teko_semibold_glyphs[glyph_index].ch != ch) {
			continue;
		}
		for (size_index = 0U; size_index < teko_semibold_glyphs[glyph_index].size_count; ++size_index) {
			if (teko_semibold_glyphs[glyph_index].sizes[size_index].size == size) {
				return teko_semibold_glyphs[glyph_index].sizes[size_index].bitmap;
			}
		}
		return 0;
	}
	return 0;
}

