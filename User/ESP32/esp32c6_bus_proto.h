typedef enum
{
  ESP32C6_BUS_STATUS_OK = 0x0000,
  ESP32C6_BUS_STATUS_ERR = 0x0001,
  ESP32C6_BUS_STATUS_BAD_MAGIC = 0x0002,
  ESP32C6_BUS_STATUS_BAD_CMD = 0x0003,
  ESP32C6_BUS_STATUS_BAD_LEN = 0x0004,
  ESP32C6_BUS_STATUS_BUSY = 0x0005,
} ESP32C6_BusStatus;

typedef struct __attribute__((packed))
{
  uint16_t magic;
  uint8_t version;
  uint8_t command;
  uint16_t sequence;
  uint16_t payload_length;
  uint16_t status;
} ESP32C6_BusFrameHeader;

typedef struct __attribute__((packed))
{
  uint32_t chip_id;
  uint32_t fw_version;
  char target[16];
  char idf_version[32];
} ESP32C6_BusInfo;

typedef struct __attribute__((packed))
{
  uint8_t pin;
  uint8_t level;
} ESP32C6_BusGpioPayload;

typedef struct __attribute__((packed))
{
  uint8_t if_type : 4;
  uint8_t if_num : 4;
  uint8_t flags;
  uint16_t len;
  uint16_t offset;
  uint16_t checksum;
  uint16_t seq_num;
  uint8_t throttle_cmd : 2;
  uint8_t reserved2 : 6;
  union
  {
    uint8_t reserved3;
    uint8_t hci_pkt_type;
    uint8_t priv_pkt_type;
  };
} ESP32C6_PayloadHeader;

typedef enum
{
  ESP32C6_HOSTED_PACKET_NONE = 0,
  ESP32C6_HOSTED_PACKET_IDLE,
  ESP32C6_HOSTED_PACKET_PRIV_INIT,
  ESP32C6_HOSTED_PACKET_PRIV_EVENT,
  ESP32C6_HOSTED_PACKET_SERIAL,
  ESP32C6_HOSTED_PACKET_WIFI,
  ESP32C6_HOSTED_PACKET_HCI,
  ESP32C6_HOSTED_PACKET_UNKNOWN,
  ESP32C6_HOSTED_PACKET_BAD_HEADER,
} ESP32C6_HostedPacketType;

typedef struct
{
  uint8_t valid;
  uint8_t chip_id;
  uint8_t capabilities;
  uint8_t raw_tp;
  uint8_t rx_queue_size;
  uint8_t tx_queue_size;
  uint32_t extended_capabilities;
  uint32_t firmware_version;
} ESP32C6_HostedInitInfo;

typedef struct
{
  ESP32C6_HostedPacketType type;
  uint8_t if_type;
  uint8_t if_num;
  uint8_t flags;
  uint8_t throttle_cmd;
  uint8_t subtype;
  uint16_t payload_len;
  uint16_t payload_offset;
  uint16_t seq_num;
  const uint8_t *payload;
} ESP32C6_HostedPacket;

