#define ESP32C6_HOSTED_SERVICE_NONE         0U
#define ESP32C6_HOSTED_SERVICE_WIFI         1U
#define ESP32C6_HOSTED_SERVICE_BLE          2U

#define ESP32C6_HOSTED_CAP_WLAN_SPI         (1U << 5)
#define ESP32C6_HOSTED_CAP_CHECKSUM         (1U << 7)

